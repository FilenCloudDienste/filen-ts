import { readFileSync, writeFileSync } from "node:fs"
import { CLDR_WINDOWS_ZONES_COMMIT } from "./windowsZonesSource"

// Writes src/features/preview/lib/windowsZones.gen.ts from CLDR's windowsZones.xml: each Windows time zone name to the
// IANA zone CLDR names for it worldwide (territory 001), for calendar files written by Windows apps. CLDR's data files
// are under the Unicode License v3; the notice is in scripts/licenses/cldr/LICENSE and the third-party notices.
//
//   curl -sSfL -o /tmp/windowsZones.xml https://raw.githubusercontent.com/unicode-org/cldr/<COMMIT>/common/supplemental/windowsZones.xml
//   pnpm exec tsx scripts/windowsZones.ts /tmp/windowsZones.xml <COMMIT>

const [path, commit] = process.argv.slice(2)

if (path === undefined || commit !== CLDR_WINDOWS_ZONES_COMMIT) {
	throw new Error(`usage: tsx scripts/windowsZones.ts <windowsZones.xml> ${CLDR_WINDOWS_ZONES_COMMIT}`)
}

const xml = readFileSync(path, "utf8")
const rows = [...xml.matchAll(/<mapZone other="([^"]+)" territory="001" type="([^"]+)"\/>/g)].map(
	match => [match[1] ?? "", match[2] ?? ""] as const
)

if (rows.length < 100) {
	throw new Error(`only ${String(rows.length)} zones read: not CLDR's windowsZones.xml`)
}

const body = rows.map(([windows, iana]) => `\t[${JSON.stringify(windows)}, ${JSON.stringify(iana)}]`).join(",\n")

writeFileSync(
	"src/features/preview/lib/windowsZones.gen.ts",
	`// Generated by scripts/windowsZones.ts from CLDR's common/supplemental/windowsZones.xml at ${commit}
// (https://github.com/unicode-org/cldr). Copyright © Unicode, Inc. Unicode License v3: see the third-party notices.
// Do not edit.

// A Windows time zone name to the IANA zone CLDR maps it to worldwide.
export const WINDOWS_ZONES: ReadonlyMap<string, string> = new Map([
${body}
])
`
)
