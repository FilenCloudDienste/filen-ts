import { readFileSync, writeFileSync } from "node:fs"
import { DICOM_DICTIONARY_EDITION as EDITION } from "./generateDicomTagsSource"

// Writes src/features/preview/lib/dicom/dicomTags.generated.ts from DICOM PS3.6 (the data dictionary) in its DocBook
// source: every data element, file meta element and directory structuring element with its VR and name, retired ones
// included, as the DICOM viewer's worker names a file's tags. The table is imported by that worker alone.
//
//   curl -sSfL -o /tmp/part06.xml https://dicom.nema.org/medical/dicom/<EDITION>/source/docbook/part06/part06.xml
//   pnpm exec tsx scripts/generateDicomTags.ts /tmp/part06.xml <EDITION>

const TABLES = ["table_6-1", "table_7-1", "table_8-1"]

const [path, edition] = process.argv.slice(2)

if (path === undefined || edition !== EDITION) {
	throw new Error(`usage: tsx scripts/generateDicomTags.ts <part06.xml> ${EDITION}`)
}

const xml = readFileSync(path, "utf8")

if (!xml.includes(`DICOM PS3.6 ${EDITION}`)) {
	throw new Error(`not PS3.6 ${EDITION}`)
}

const ENTITIES: Readonly<Record<string, string>> = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'" }

function text(cell: string): string {
	return cell
		.replace(/<[^>]+>/g, "")
		.replace(/&(amp|lt|gt|quot|apos);/g, (_, name: string) => ENTITIES[name] ?? "")
		.replace(/&#x([0-9a-f]+);/gi, (_, hex: string) => String.fromCodePoint(Number.parseInt(hex, 16)))
		.replace(/[\u200b\u00a0]/g, " ")
		.replace(/\s+/g, " ")
		.trim()
}

function tableBody(id: string): string {
	const start = xml.indexOf(`xml:id="${id}"`)
	const body = xml.indexOf("<tbody>", start)
	const end = xml.indexOf("</tbody>", body)

	if (start === -1 || body === -1 || end === -1) {
		throw new Error(`${id} not found`)
	}

	return xml.slice(body, end)
}

const rows = new Map<string, string>()

for (const id of TABLES) {
	for (const [row] of tableBody(id).matchAll(/<tr[\s\S]*?<\/tr>/g)) {
		const cells = [...row.matchAll(/<td[\s\S]*?<\/td>/g)].map(([cell]) => text(cell))
		const [tag, name, , vr] = cells
		const match = /^\(([0-9A-Fx]{4}),([0-9A-Fx]{4})\)$/i.exec(tag ?? "")

		if (match === null || name === undefined || name === "" || vr === undefined) {
			continue
		}

		const key = `${match[1] ?? ""}${match[2] ?? ""}`.toUpperCase().replace(/X/g, "x")
		// A VR the standard leaves open ("US or SS", "See Note") is shown as written; nothing reads it as a type.
		const shownVr = /^[A-Z]{2}$/.test(vr) ? vr : vr.replace(/ or /g, "/")

		rows.set(key, `${key}\t${shownVr}\t${name}`)
	}
}

if (rows.size < 4000) {
	throw new Error(`only ${String(rows.size)} elements read: not PS3.6's registry`)
}

const lines = [...rows.values()].sort()

writeFileSync(
	"src/features/preview/lib/dicom/dicomTags.generated.ts",
	`// Generated by scripts/generateDicomTags.ts from DICOM PS3.6 ${EDITION} (the data dictionary: tables 6-1, 7-1 and 8-1).
// DICOM® is the registered trademark of NEMA for its standards publications; the dictionary's text is © NEMA. Do not
// edit. Imported by the DICOM viewer's worker only.

// One element a line: its tag as eight hex digits ("x" for a digit any value takes, as in 60xx3000), its VR, its name.
export const DICOM_TAGS =
	${JSON.stringify(lines.join("\n"))}
`
)
