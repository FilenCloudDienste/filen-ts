// Past this share of its bytes, a download whose thumbnail nobody wants any more finishes anyway: the
// rest costs less than starting over the next time the cell scrolls into view.
const DOWNLOAD_COMMIT_FRACTION = 0.5

// pdf and svg are the generators that pull a whole file into JS memory, through the same buffered
// download the preview overlay uses (usePreviewBytes) — or straight from the bytes a preview already
// holds. The returned buffer is the caller's own, so a consumer may transfer it.
async function downloadWholeFile(item: BaseFileItem, signal: AbortSignal): Promise<Uint8Array> {
	const held = getPreviewBytes(previewCacheScope("authed", undefined), item.data.uuid)

	if (held !== undefined) {
		return held.slice()
	}

	signal.throwIfAborted()

	const token = crypto.randomUUID()
	const stop = (): void => {
		void sdkApi.cancelPreviewDownloadIfEarly(token, DOWNLOAD_COMMIT_FRACTION)
	}

	signal.addEventListener("abort", stop, { once: true })

	try {
		return await runOp(sdkApi.downloadFileBytes(narrowToAnyFile(item), token))
	} finally {
		signal.removeEventListener("abort", stop)
	}
}

// Persisting the generated bytes (storeThumbnail) is NOT a generator's job — features/drive/lib/thumbnails.ts's
// own generate() already does that once, uniformly, for whatever any registered generator returns. A
// second persist call here would double-write the same uuid to OPFS on every generated thumbnail.

// Maps the worker DTO onto the service's own three-way result. The three byte-less arms are SETTLED
// verdicts about the file's content, so they become "unavailable" (remembered for the session, no
// blacklist strike) rather than the plain failure a dropped call is. An empty buffer is treated as a
// failure, not a verdict — bytes that claim to be a thumbnail but aren't are a bug somewhere, and the
// blacklist is the right place for it.
function asGenerationResult(result: SdkThumbnailResult): ThumbGenerationResult {
	if (result.type === "thumbnail") {
		return result.bytes.length === 0 ? { type: "failed" } : { type: "bytes", bytes: result.bytes }
	}

	return { type: "unavailable", reason: result.type }
}

// EVERY still image on the drive — plain raster, HEIC and camera RAW alike — decoded by the Rust SDK.
// Nothing is downloaded into JS: the SDK reads the ranges it needs itself (the cheap embedded-preview
// probe first, at worst a whole-file range read inside wasm), and only the small webp result crosses
// back. That is the whole point of routing RAW here — a 90 MB NEF usually costs a couple of range
// reads because the camera already embedded a full-size JPEG in it.
//
// The request is 384x768 rather than square, and lossy; THUMB_SDK_MAX_HEIGHT and
// THUMB_SDK_LOSSY_QUALITY carry the reasoning for the shape and the encode respectively.
//
// A thrown call (the worker died, the client is gone, the read never landed) is a transient failure
// and counts toward the blacklist; the SDK's own unsupported/overBudget/corrupt answers do not.
//
// Never stopped once started: the SDK's in-memory thumbnail call takes no ManagedFuture, and it is
// usually a couple of range reads anyway.
export const generateSdkThumb: ThumbGenerator = async item => {
	try {
		const result = await sdkApi.makeSdkThumbnail(narrowToAnyFile(item), THUMB_MAX_DIM, THUMB_SDK_MAX_HEIGHT, THUMB_SDK_LOSSY_QUALITY)

		return asGenerationResult(result)
	} catch (e) {
		log.warn("thumb-generators", "generateSdkThumb: sdk call failed", item.data.uuid, e)

		return { type: "failed" }
	}
}

// Thumbnails a file the client STILL HOLDS, straight after its upload lands, so the freshly-patched
// listing row never triggers a download of bytes that are already on this machine. Seeded into the
// thumbnail service (seedThumbnail) rather than merely written to OPFS: the row's tile asks for its
// thumbnail in the very next commit, and only a pending-map entry makes that tile JOIN this
// production instead of racing it with a server-side one.
//
// Gated on thumbnailCategory of the uploaded file, not on a local extension guess — that keeps the
// SDK's own canMakeThumbnail as the single source of truth here too. An svg, a video and a pdf are
// made here too, by the very code the drive-side arm runs, from the local file instead of a download.
//
// Sequenced AFTER the upload resolves, never overlapped with it: both legs read the same browser File,
// and an overlap would be correct but would read the same local file twice at once for no gain.
// Synchronous and fire-and-forget by design: the transfer is already settled and the row is already
// in the listing, so blocking either on a cache warm would only delay the upload summary toast.
export function warmUploadThumbnail(uploaded: SdkFile, file: File): void {
	const item = narrowItem(uploaded)
	const category = thumbnailCategory(item)

	// Its size gate is already in the category. The rasteriser's verdicts are about the markup itself,
	// which the drive-side arm would read identically; only a failure leaves the uuid to it.
	if (category === "svg") {
		seedThumbnail(item, async () => {
			const result = await rasterizeSvgThumb(await file.text())

			return result.type === "bytes" ? result : { type: result.type === "unavailable" ? "none" : "unanswered" }
		})

		return
	}

	if (category === "video") {
		// Typed as the drive-side arm's stream is; a same-type slice is a view of the File, not a copy. An
		// item that arm would never stream gets no seat: it fails there without a request.
		const contentType = allowedMediaContentType(item)

		if (contentType !== null) {
			// A file the element cannot decode is left unanswered: the drive-side arm still has its keyframe read.
			seedLocalThumb(item, "video", async () => {
				const result = await videoThumb(
					uploaded.uuid,
					defer => {
						const url = URL.createObjectURL(file.slice(0, file.size, contentType))

						defer(() => {
							URL.revokeObjectURL(url)
						})

						return url
					},
					localVideoError
				)

				return result.type === "undecodable" ? null : result
			})
		}

		return
	}

	if (category === "pdf") {
		seedLocalThumb(item, "pdf", async () => {
			let bytes: Uint8Array

			try {
				bytes = new Uint8Array(await file.arrayBuffer())
			} catch (e) {
				log.warn("thumb-generators", "warmUploadThumbnail: local read failed", uploaded.uuid, e)

				return null
			}

			return await renderPdfThumb(bytes, uploaded.uuid)
		})

		return
	}

	if (category !== "sdk") {
		return
	}

	// Size-gated where the drive-side arm deliberately is not, because the two arms do not decode under
	// the same budget: makeThumbnailFromStream buffers the source WHOLE and takes its length off the
	// SDK's decode budget, where the drive arm pays a constant three chunk slots for a source it reads by
	// range. Past THUMB_WARM_SIZE_GATE what is left cannot afford the 256x512 this asks for, and the
	// result is not a refusal but a SMALLER thumbnail — which the seat then persists as the uuid's
	// durable cache entry, displacing the full-size one the drive arm would have produced. A browser
	// File knows its own size, so nothing is read to decide this.
	if (BigInt(file.size) > THUMB_WARM_SIZE_GATE) {
		return
	}

	// In an image generation slot: it takes the SDK's decoder exactly as the drive-side arm would.
	seedThumbnail(item, () =>
		withGenerationSlot("sdk", async (): Promise<ThumbSeedResult> => {
			const result = await sdkApi.makeSdkThumbnailFromFile(file, THUMB_MAX_DIM, THUMB_SDK_MAX_HEIGHT, THUMB_SDK_LOSSY_QUALITY)

			if (result.type === "thumbnail") {
				return { type: "bytes", bytes: result.bytes }
			}

			log.info("thumb-generators", "warmUploadThumbnail: no thumbnail", uploaded.uuid, result.type)

			// `unsupported` and `corrupt` are answers about the bytes themselves, which the drive-side arm
			// sniffs the same way and would answer the same. `overBudget` is not: the budget this arm decodes
			// under shrank by the whole source, so a decoder peak that does not fit HERE can still fit the
			// drive arm's near-full budget — a verdict about this arm's own buffering, not about the file.
			return result.type === "overBudget" ? { type: "unanswered" } : { type: "none" }
		})
	)
}

// A local video or pdf production: a browser decode, so it takes a generation slot like the drive-side
// one it replaces (see withGenerationSlot). Its failure is settled as "none": the drive-side arm would
// run this same code over these same bytes, only after downloading them. Null says nothing about the
// file: a local file that could not be read, or a video the drive-side arm reads another way.
function seedLocalThumb(item: DriveItem, category: "video" | "pdf", produce: () => Promise<ThumbGenerationResult | null>): void {
	seedThumbnail(item, () =>
		withGenerationSlot(category, async (): Promise<ThumbSeedResult> => {
			const result = await produce()

			if (result === null) {
				return { type: "unanswered" }
			}

			return result.type === "bytes" ? result : { type: "none" }
		})
	)
}

// The element answered that it cannot decode these bytes, as opposed to a read that failed or stopped.
// `settled` unless the answer may also have been a read that failed in passing.
class VideoUndecodableError extends Error {
	public readonly settled: boolean

	public constructor(message: string, settled: boolean) {
		super(message)

		this.name = "VideoUndecodableError"
		this.settled = settled
	}
}

// The element gave up on its source, with MediaError `code`.
class VideoElementError extends Error {
	public readonly code: number | undefined

	public constructor(message: string, code: number | undefined) {
		super(message)

		this.name = "VideoElementError"
		this.code = code
	}
}

// Whether an element's MediaError `code` on `url` is a verdict about the bytes; `signal` ends the check.
// "unsettled": most likely the format, but possibly a read that failed in passing.
type VideoErrorVerdict = MediaFailureKind | "unsettled"
type VideoErrorClassifier = (code: number, url: string, signal: AbortSignal) => Promise<VideoErrorVerdict>

// A local file's bytes are always readable, so either format code is the file.
function localVideoError(code: number): Promise<VideoErrorVerdict> {
	return Promise.resolve(isFormatMediaError(code) ? "format" : "other")
}

// Resolves once `event` fires, or rejects if the element errors first — a corrupt/unplayable stream
// must fail promptly rather than sit until the deadline — or once `signal` aborts.
function waitForVideoEvent(video: HTMLVideoElement, event: "loadedmetadata" | "loadeddata" | "seeked", signal: AbortSignal): Promise<void> {
	return new Promise((resolve, reject) => {
		const cleanup = () => {
			video.removeEventListener(event, onEvent)
			video.removeEventListener("error", onError)
			signal.removeEventListener("abort", onAbort)
		}
		const onEvent = () => {
			cleanup()
			resolve()
		}
		const onError = () => {
			cleanup()
			const message = `video element errored before ${event}`

			reject(new VideoElementError(message, video.error?.code))
		}
		const onAbort = () => {
			cleanup()
			reject(new Error(`stopped waiting for ${event}`, { cause: signal.reason }))
		}

		if (signal.aborted) {
			onAbort()

			return
		}

		video.addEventListener(event, onEvent, { once: true })
		video.addEventListener("error", onError, { once: true })
		signal.addEventListener("abort", onAbort, { once: true })
	})
}

const VIDEO_GENERATE_TIMEOUT_MS = 15_000

// Mean luma of the element's current frame, from a tiny draw of it; a missing context counts as bright,
// which keeps the first frame.
function currentFrameLuma(video: HTMLVideoElement): number {
	const ctx = new OffscreenCanvas(SAMPLE_WIDTH, SAMPLE_HEIGHT).getContext("2d", { willReadFrequently: true })

	if (ctx === null) {
		return Number.POSITIVE_INFINITY
	}

	ctx.drawImage(video, 0, 0, SAMPLE_WIDTH, SAMPLE_HEIGHT)

	return meanLuma(ctx.getImageData(0, 0, SAMPLE_WIDTH, SAMPLE_HEIGHT).data)
}

// One frame of the video `openSource` resolves to, drawn into a thumbnail. Both arms share it: the
// drive-side one plays the SW's Range stream, the upload warm the local file.
//
// Only the metadata is preloaded, and each seek then fetches just the data for the frame it lands on:
// buffering ahead ("auto") downloaded and decrypted megabytes that the teardown below then cancelled. A
// black first frame (an opening fade) gets one more, bounded seek (driveVideoThumbSeeks). The waits end
// at the deadline themselves, so a stream that never fires its event or error settles this callback and
// its deferred cleanup empties the element, ending the stream; runTimeout alone could only stop waiting
// for it. `signal` stops the generation only until the frame has loaded: past that, all that is left is
// one draw.
//
// "undecodable" is the element's verdict that it cannot decode the bytes (an error `classify` names a
// format one while the source is still open, or metadata without a picture), `settled` unless that error
// may also have been a passing read failure; a failed or stopped read stays "failed".
async function videoThumb(
	uuid: string,
	openSource: (defer: DeferFn) => Promise<string> | string,
	classify: VideoErrorClassifier,
	signal?: AbortSignal
): Promise<ThumbGenerationResult | { type: "undecodable"; settled: boolean }> {
	const deadline = AbortSignal.timeout(VIDEO_GENERATE_TIMEOUT_MS)
	const beforeFirstFrame = signal === undefined ? deadline : AbortSignal.any([signal, deadline])

	const result: Result<Uint8Array> = await runTimeout(async defer => {
		beforeFirstFrame.throwIfAborted()

		const url = await openSource(defer)

		const video = document.createElement("video")

		video.muted = true
		video.playsInline = true
		video.preload = "metadata"
		video.src = url

		// Removing the attribute empties the element. `src = ""` instead resolves against the page, so
		// Firefox loads the site root as media (and the service worker reports the failed load).
		defer(() => {
			video.removeAttribute("src")
			video.load()
		})

		const waitFor = async (event: "loadedmetadata" | "loadeddata" | "seeked"): Promise<void> => {
			try {
				await waitForVideoEvent(video, event, beforeFirstFrame)
			} catch (e) {
				if (e instanceof VideoElementError && e.code !== undefined) {
					const verdict = await classify(e.code, url, beforeFirstFrame)

					if (verdict !== "other") {
						throw new VideoUndecodableError(e.message, verdict === "format")
					}
				}

				throw e
			}
		}

		await waitFor("loadedmetadata")

		if (video.videoWidth === 0) {
			throw new VideoUndecodableError("no picture in the metadata", true)
		}

		// `seeked` fires once the frame at the new position is decoded. An indeterminate duration (NaN —
		// e.g. a stream with no known Content-Length) falls back to frame 0, where seeking to the position
		// the video is already at would never fire `seeked`: that one loads the first frame instead, which
		// a metadata-only preload need not do on its own.
		const duration = video.duration

		if (Number.isFinite(duration) && duration > 0) {
			const { first, retry } = driveVideoThumbSeeks(duration)

			video.currentTime = first

			await waitFor("seeked")

			if (retry !== null && isDark(currentFrameLuma(video))) {
				video.currentTime = retry

				await waitFor("seeked")
			}
		} else if (video.readyState < video.HAVE_CURRENT_DATA) {
			video.preload = "auto"

			await waitFor("loadeddata")
		}

		const { width, height } = fitWithin(video.videoWidth, video.videoHeight, THUMB_MAX_DIM)
		const canvas = new OffscreenCanvas(width, height)
		const ctx = canvas.getContext("2d")

		if (ctx === null) {
			throw new Error("could not create an OffscreenCanvas 2D context")
		}

		ctx.drawImage(video, 0, 0, width, height)

		const blob = await encodeCanvasThumb(canvas)

		return new Uint8Array(await blob.arrayBuffer())
	}, VIDEO_GENERATE_TIMEOUT_MS)

	if (!result.success) {
		if (result.error instanceof VideoUndecodableError) {
			return { type: "undecodable", settled: result.error.settled }
		}

		if (signal?.aborted !== true) {
			log.warn("thumb-generators", "videoThumb failed", uuid, result.error)
		}

		return { type: "failed" }
	}

	return { type: "bytes", bytes: result.data }
}

// canPlayType per content type, asked once: the answer is the browser's and does not change.
const canPlayAnswers = new Map<string, boolean>()

function elementCanPlay(query: string): boolean {
	let answer = canPlayAnswers.get(query)

	if (answer === undefined) {
		answer = document.createElement("video").canPlayType(query) !== ""
		canPlayAnswers.set(query, answer)
	}

	return answer
}

