const KEYFRAME_BOX = { width: THUMB_MAX_DIM, height: THUMB_MAX_DIM }

const KEYFRAME_WORKER_IDLE_MS = 30_000

// A capture that has not answered by now has a stuck decoder or a dead worker; the worker is replaced.
const KEYFRAME_CAPTURE_TIMEOUT_MS = 20_000

interface KeyframeWorker {
	worker: Worker
	remote: Comlink.Remote<FrameWorkerApi>
}

// Drive's own probe scheduler, frame generator and frame worker. The Videos probe records and frame hints
// are shared, so a file either feature has looked at costs the other no read; the session caps, gates and
// failure counts are drive's, so a scrolled directory neither spends Videos' budgets nor queues behind them.
interface KeyframeServices {
	probes: ProbeService
	frames: FrameGenerator
	worker: IdleResource<KeyframeWorker>
}

let keyframeServices: KeyframeServices | null = null

function keyframeWorker(FrameWorker: new () => Worker): IdleResource<KeyframeWorker> {
	const resource = idleResource<KeyframeWorker>(
		() => {
			const worker = new FrameWorker()
			const held: KeyframeWorker = { worker, remote: Comlink.wrap<FrameWorkerApi>(worker) }

			worker.addEventListener("error", () => {
				// A deploy that changed this worker removes its old file (appUpdate.ts).
				recoverIfNewerBuild()
				resource.invalidate(held)
			})

			return held
		},
		({ worker, remote }) => {
			remote[Comlink.releaseProxy]()
			worker.terminate()
		},
		KEYFRAME_WORKER_IDLE_MS
	)

	return resource
}

function captureKeyframe(resource: IdleResource<KeyframeWorker>, params: FrameCaptureParams): Promise<FrameCaptureResult> {
	return resource.use(async held => {
		let timer: ReturnType<typeof setTimeout> | undefined
		const deadline = new Promise<never>((_resolve, reject) => {
			timer = setTimeout(() => {
				resource.invalidate(held)
				reject(new Error("keyframe capture timed out"))
			}, KEYFRAME_CAPTURE_TIMEOUT_MS)
		})

		try {
			return await Promise.race([held.remote.capture(Comlink.transfer(params, [params.port])), deadline])
		} finally {
			clearTimeout(timer)
		}
	})
}

// Made on first use; the frame worker starts only once a capture needs it.
function keyframeServicesNow(): KeyframeServices {
	keyframeServices ??= createKeyframeServices()

	return keyframeServices
}

function createKeyframeServices(): KeyframeServices {
	const worker = keyframeWorker(FrameWorker)
	const probes = new ProbeService({
		readProbe: (file, uuid, tier, token) => sdkApi.readVideoProbe(file, uuid, tier, token),
		cancel: (token, finishWithin) => {
			void (finishWithin === undefined
				? sdkApi.cancelPreviewDownload(token)
				: sdkApi.cancelPreviewDownloadUnlessFinishing(token, finishWithin))
		},
		records: probeRecords,
		reads: rangeReads,
		isOnline: () => onlineManager.isOnline(),
		now: () => Date.now()
	})
	// No dwell and no wait for playback to end: the thumbnail service has already decided the cell is
	// wanted, and both waits would hold its generation slot. Playback still narrows the range-read
	// budget each read takes a permit from, and the element arm never waited for it either.
	const frames = new FrameGenerator({
		openPort: async (file, token) => {
			const { port1, port2 } = new MessageChannel()

			await sdkApi.openRangePort(Comlink.transfer(port1, [port1]), file, token)

			return port2
		},
		cancel: token => {
			void sdkApi.cancelPreviewDownload(token)
		},
		capture: params => captureKeyframe(worker, params),
		hints: frameHints,
		reads: {
			acquire: rank => rangeReads.acquire(rank),
			release: () => {
				rangeReads.release()
			},
			whenPlaybackIdle: () => Promise.resolve()
		},
		sleep: () => Promise.resolve(),
		now: () => Date.now()
	})

	onlineManager.subscribe(online => {
		if (online) {
			probes.onReconnect()
		}
	})

	return { probes, frames, worker }
}

// Logout: drive's probes and frames abort, their session spending and verdicts go, and the frame worker's
// heap goes once idle. Makes nothing never used.
export function resetDriveKeyframes(): void {
	if (keyframeServices !== null) {
		keyframeServices.probes.reset()
		keyframeServices.frames.reset()
		keyframeServices.worker.disposeIfIdle()
	}
}

// The frame generator's keyframe read, for a video the element cannot decode or stream: the card probe
// (kv-cached per uuid) locates the keyframe index, then only the keyframe's bytes are read through the
// SDK worker's range port and decoded with VideoDecoder, within drive's own session budget. A file with
// no frame to find (no video track, no keyframe index, a codec without a decoder) is a settled verdict;
// everything else (offline, budgets spent, a failed read) is a failure.
async function keyframeThumb(item: BaseFileItem, signal: AbortSignal): Promise<ThumbGenerationResult> {
	// A function, so each check reads the signal anew across the awaits.
	const stopped = (): boolean => signal.aborted
	const { probes, frames } = keyframeServicesNow()
	const uuid = item.data.uuid
	const file = narrowToAnyFile(item)
	const record = await probes.request({ uuid, file }, "card", { signal, rank: keyframeRank })

	if (record === null || stopped()) {
		return { type: "failed" }
	}

	const probe = record.probe

	// A read that ran anyway: what it says about the file's kind is kept (an audio-only .webm loses its
	// video glyph and its thumbnail attempts).
	recordProbeVerdict({ uuid, name: driveItemName(item), mime: driveItemMime(item), size: item.data.size }, probe)

	if (probe === null || !frameEligible(probe)) {
		return { type: "unavailable", reason: "unsupported" }
	}

	const frame = await frames.generate({
		target: { uuid, file, size: Number(item.data.size) },
		probe,
		box: KEYFRAME_BOX,
		signal,
		rank: keyframeRank
	})

	if (frame !== null) {
		return { type: "bytes", bytes: frame.bytes }
	}

	if (stopped()) {
		return { type: "failed" }
	}

	return isSettledMiss(await frameHints.get(uuid)) ? { type: "unavailable", reason: "unsupported" } : { type: "failed" }
}

// MEDIA_ERR_SRC_NOT_SUPPORTED on the worker's stream is also what a fetch that failed before the metadata
// raises: offline, a registration the worker lost, or an SDK read that failed while the registration held
// (a server error, a rate limit, a timeout). The worker's registry tells a lost registration apart without
// a range read (a read of even one byte downloads a whole SDK chunk again); the check ends with `signal`.
// A held registration, or a worker too old to be asked, cannot rule out a failed read, so that answer
// takes the keyframe read this once without settling the element out for the session.
const MEDIA_ERR_SRC_NOT_SUPPORTED = 4

async function streamedVideoError(code: number, url: string, signal: AbortSignal): Promise<VideoErrorVerdict> {
	if (code !== MEDIA_ERR_SRC_NOT_SUPPORTED) {
		return isFormatMediaError(code) ? "format" : "other"
	}

	if (!onlineManager.isOnline() || signal.aborted) {
		return "other"
	}

	const status = await new Promise<PreviewStreamStatus | null>(resolve => {
		const unsubscribe = onAbort(signal, () => {
			resolve(null)
		})

		void previewStreamStatus(previewStreamIdOf(url)).then(
			answer => {
				unsubscribe()
				resolve(answer)
			},
			() => {
				unsubscribe()
				resolve(null)
			}
		)
	})

	return status === "present" || status === "unknown" ? "unsettled" : "other"
}

// The hidden <video> on the SW's Range stream first, where it can play the file; the keyframe read
// where it cannot, or once it has failed to decode it. A failed or timed-out stream is not retried
// through the keyframe read, which would only double the reads.
export const generateVideoThumb: ThumbGenerator = async (item, signal) => {
	const stopped = (): boolean => signal.aborted

	if (stopped()) {
		return { type: "failed" }
	}

	const uuid = item.data.uuid
	const contentType = driveVideoElementType(allowedMediaContentType(item), elementCanPlay, elementUndecodable.has(uuid))

	// Awaited rather than sampled: a page is uncontrolled for a moment after every worker install or
	// update, the ordinary state of a first load. Where no worker is registered at all it returns at once.
	if (contentType !== null && (await waitForMediaStream())) {
		// Released once the element is emptied (the deferred cleanups run last-registered first), so the
		// worker's registry does not keep this one-frame registration until newer ones crowd it out.
		const result = await videoThumb(
			uuid,
			defer => {
				const id = crypto.randomUUID()

				defer(() => {
					releasePreviewStream(id)
				})

				return previewStreamUrl(narrowToAnyFile(item), driveItemName(item), contentType, id, { transient: true })
			},
			streamedVideoError,
			signal
		)

		if (result.type !== "undecodable") {
			return result
		}

		if (result.settled) {
			elementUndecodable.add(uuid)
		}

		if (stopped()) {
			return { type: "failed" }
		}
	}

	return await keyframeThumb(item, signal)
}

const SVG_RENDER_TIMEOUT_MS = 10_000

// Two renders at a time: an svg's layout and paint run on the main thread, where nothing can interrupt
// them, so a costly document never has more than one other beside it.
const svgRenderGate = new Semaphore(2)

async function inSvgRenderSlot<T>(render: () => Promise<T>): Promise<T> {
	await svgRenderGate.acquire()

	try {
		return await render()
	} finally {
		svgRenderGate.release()
	}
}

// Rasterises an svg document into a thumbnail. Only ever through an <img>: the SVG spec's secure mode
// for images runs no script, fires no event handler and fetches no external resource, so the markup
// never has to be sanitised to be safe (prepareSvgThumb refuses the entity bombs that mode does not
// cover). The blob URL is same-origin, so the canvas stays readable, except where an engine taints it
// for an svg anyway (Safari, for a <foreignObject>): that is a settled "unsupported", not a failure.
// Drawn at the thumbnail's own size, so the vector is rasterised once, crisply, at the size shown.
export async function rasterizeSvgThumb(text: string): Promise<ThumbGenerationResult> {
	const prepared = prepareSvgThumb(text, THUMB_MAX_DIM)

	if (prepared.type === "rejected") {
		return { type: "unavailable", reason: prepared.reason }
	}

	const result = await inSvgRenderSlot(() =>
		runTimeout<ThumbGenerationResult>(async defer => {
			const url = URL.createObjectURL(new Blob([prepared.markup], { type: "image/svg+xml" }))

			defer(() => {
				URL.revokeObjectURL(url)
			})

			const image = new Image(prepared.width, prepared.height)

			image.src = url

			try {
				await image.decode()
			} catch {
				return { type: "unavailable", reason: "corrupt" }
			}

			const canvas = new OffscreenCanvas(prepared.width, prepared.height)
			const ctx = canvas.getContext("2d")

			if (ctx === null) {
				throw new Error("could not create an OffscreenCanvas 2D context")
			}

			ctx.drawImage(image, 0, 0, prepared.width, prepared.height)

			let blob: Blob

			try {
				blob = await encodeCanvasThumb(canvas, { alpha: true })
			} catch (e) {
				if (e instanceof DOMException && e.name === "SecurityError") {
					return { type: "unavailable", reason: "unsupported" }
				}

				throw e
			}

			return { type: "bytes", bytes: new Uint8Array(await blob.arrayBuffer()) }
		}, SVG_RENDER_TIMEOUT_MS)
	)

	if (!result.success) {
		log.warn("thumb-generators", "rasterizeSvgThumb failed", result.error)

		return { type: "failed" }
	}

	return result.data
}

// Small by construction (THUMB_SVG_SIZE_GATE), so the whole document is read like a pdf's: the
// rasteriser needs the markup, not a stream. Once the markup is in hand the render always runs.
export const generateSvgThumb: ThumbGenerator = async (item, signal) => {
	let bytes: Uint8Array

	try {
		bytes = await downloadWholeFile(item, signal)
	} catch (e) {
		if (!signal.aborted) {
			log.warn("thumb-generators", "generateSvgThumb: download failed", item.data.uuid, e)
		}

		return { type: "failed" }
	}

	return await rasterizeSvgThumb(new TextDecoder().decode(bytes))
}

// One pdf.js worker shared by every PDF thumbnail, instead of one spun up and torn down per file.
// Passed to getDocument explicitly, so a task's destroy() ends only its own document and never the
// worker (pdf.js destroys only a worker it created itself), while pdfViewer.tsx's previews keep
// their own. Torn down once no generation has used it for a while.
const PDF_THUMB_WORKER_IDLE_MS = 30_000

let pdfThumbWorker: IdleResource<PDFWorker> | null = null

// Page 1 of a whole pdf, drawn into a thumbnail. Both arms share it: the drive-side one downloads the
// bytes, the upload warm reads them from the local file.
async function renderPdfThumb(bytes: Uint8Array, uuid: string): Promise<ThumbGenerationResult> {
	// Mirrors pdfViewer.tsx's own worker-src setup (duplicated rather than imported: that file is a
	// React component this module must not depend on). Read when the shared worker is constructed.
	GlobalWorkerOptions.workerSrc = new URL("pdfjs-dist/build/pdf.worker.mjs", import.meta.url).href

	pdfThumbWorker ??= idleResource(
		() => new PDFWorker(),
		worker => {
			worker.destroy()
		},
		PDF_THUMB_WORKER_IDLE_MS
	)

	return await pdfThumbWorker.use<ThumbGenerationResult>(async worker => {
		const task = getDocument({ data: bytes, worker })

		try {
			// No onPassword handler is registered — pdf.js rejects task.promise with the password exception
			// instead of waiting on a handler that will never answer (verified against the installed 6.1.200
			// source), so a password-protected file fails this generation promptly rather than hanging.
			const doc = await task.promise
			const page = await doc.getPage(1)
			const baseViewport = page.getViewport({ scale: 1 })
			const fitted = fitWithin(baseViewport.width, baseViewport.height, THUMB_MAX_DIM)
			const viewport = page.getViewport({ scale: fitted.width / baseViewport.width })

			const canvas = document.createElement("canvas")

			canvas.width = fitted.width
			canvas.height = fitted.height

			const renderTask = page.render({ canvas, viewport })

			await renderTask.promise

			const blob = await encodeCanvasThumb(canvas)

			return { type: "bytes", bytes: new Uint8Array(await blob.arrayBuffer()) }
		} catch (e) {
			log.warn("thumb-generators", "renderPdfThumb: render failed", uuid, e)
			// pdf.worker is its own file: a deploy that changed it fails documents in older tabs.
			recoverIfNewerBuild()

			return { type: "failed" }
		} finally {
			await task.destroy()
		}
	})
}

// Once the bytes are in hand the render always runs: page 1 costs far less than the download did.
export const generatePdfThumb: ThumbGenerator = async (item, signal) => {
	let bytes: Uint8Array

	try {
		bytes = await downloadWholeFile(item, signal)
	} catch (e) {
		if (!signal.aborted) {
			log.warn("thumb-generators", "generatePdfThumb: download failed", item.data.uuid, e)
		}

		return { type: "failed" }
	}

	return await renderPdfThumb(bytes, item.data.uuid)
}

