import { createHash } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { unzipSync } from "fflate"
import { format, resolveConfig } from "prettier"
import { NodeKind, parseXml } from "../core/xml/index"
import { SOURCE as GEOMETRY_SOURCE, encodeShape } from "./presetGeometry"

// Generates src/core/presentation/render/warps.generated.ts from the preset text warp definitions that ship with
// ECMA-376 Part 1 (5th edition, annex L, OfficeOpenXML-DrawingMLGeometries.zip; §20.1.10.76 ST_TextShapeType), in
// the preset geometry encoding (program.ts). Every archive layer is checked against its pinned SHA-256.
//
//   pnpm run generate:text-warp [<ECMA-376-1 zip | OfficeOpenXML-DrawingMLGeometries.zip | presetTextWarpDefinitions.xml>]
//
// Without an argument the Part 1 archive is downloaded from ecma-international.org.

export const OUTPUT = fileURLToPath(new URL("../core/presentation/render/warps.generated.ts", import.meta.url))

export const SOURCE = {
	...GEOMETRY_SOURCE,
	warps: "presetTextWarpDefinitions.xml",
	warpsSha256: "89640bd4aeedfa2c578d1d1acc50d569865ebdef315fd4b468087c25e36acada"
} as const

function sha256(bytes: Uint8Array): string {
	return createHash("sha256").update(bytes).digest("hex")
}

function extract(archive: Uint8Array, name: string, expected: string): Uint8Array {
	const entry = unzipSync(archive, { filter: file => file.name === name })[name]

	if (entry === undefined) throw new Error(`${name} is missing from the archive`)
	if (sha256(entry) !== expected) throw new Error(`${name} does not match its pinned SHA-256`)

	return entry
}

// The definitions file from whichever layer `bytes` is.
export function warpDefinitions(bytes: Uint8Array): Uint8Array {
	const digest = sha256(bytes)

	if (digest === SOURCE.warpsSha256) return bytes
	if (digest === SOURCE.geometriesSha256) return extract(bytes, SOURCE.warps, SOURCE.warpsSha256)
	if (digest === SOURCE.sha256)
		return extract(extract(bytes, SOURCE.geometries, SOURCE.geometriesSha256), SOURCE.warps, SOURCE.warpsSha256)

	throw new Error("Input matches none of the pinned ECMA-376 files")
}

export function warpTable(definitions: Uint8Array): Map<string, string> {
	// textArchUp's adjust default is the built-in "cd2" (half a circle, 10800000 60000ths of a degree); the encoding
	// keeps adjust defaults as literals.
	const text = new TextDecoder().decode(definitions).replaceAll('fmla="val cd2"', 'fmla="val 10800000"')
	const document = parseXml(new TextEncoder().encode(text))
	const root = document.documentElement()
	const out = new Map<string, string>()

	for (let warp = document.firstChildElement(root); warp >= 0; warp = document.nextSiblingElement(warp)) {
		if (document.kinds[warp] !== NodeKind.Element) continue

		out.set(document.localName(warp), encodeShape(document, warp))
	}

	return out
}

export async function renderTable(table: ReadonlyMap<string, string>): Promise<string> {
	const entries = [...table].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
	const source = [
		`// Generated by \`pnpm run generate:text-warp\` from ECMA-376 Part 1 (5th edition) ${SOURCE.warps}`,
		`// (SHA-256 ${SOURCE.warpsSha256}), © Ecma International, see THIRD_PARTY_NOTICES.md.`,
		"// Do not edit. Encoding: core/drawingml/geometry/program.ts.",
		"",
		"export const PRESET_TEXT_WARP: Readonly<Record<string, string>> = {",
		...entries.map(([name, encoded]) => `\t${JSON.stringify(name)}: ${JSON.stringify(encoded)},`),
		"}",
		""
	].join("\n")

	return format(source, { ...(await resolveConfig(OUTPUT)), filepath: OUTPUT })
}

async function main(): Promise<void> {
	const path = process.argv[2]
	let bytes: Uint8Array

	if (path !== undefined) {
		bytes = new Uint8Array(readFileSync(path))
	} else {
		const response = await fetch(SOURCE.url)

		if (!response.ok) throw new Error(`${SOURCE.url}: HTTP ${response.status}`)

		bytes = new Uint8Array(await response.arrayBuffer())
	}

	writeFileSync(OUTPUT, await renderTable(warpTable(warpDefinitions(bytes))))
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main()
