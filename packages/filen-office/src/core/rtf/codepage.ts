// Single bytes the Mac CJK code pages add to their Windows supersets (Apple JAPANESE, CHINTRAD, CHINSIMP),
// with each one's lead bytes so a trail byte is never taken for one. Mac Korean's extras are not mapped.
interface MacExtras {
	readonly lead: (byte: number) => boolean
	readonly bytes: ReadonlyMap<number, number>
}

// 0xA0 no-break space, 0xFD-0xFF © ™ …; 0x80 differs per code page.
function macBytes(byte80: number): ReadonlyMap<number, number> {
	return new Map([
		[0x80, byte80],
		[0xa0, 0xa0],
		[0xfd, 0xa9],
		[0xfe, 0x2122],
		[0xff, 0x2026]
	])
}

const MAC_EXTRAS: ReadonlyMap<number, MacExtras> = new Map([
	[10001, { lead: (byte: number) => (byte >= 0x81 && byte <= 0x9f) || (byte >= 0xe0 && byte <= 0xfc), bytes: macBytes(0x5c) }],
	[10002, { lead: (byte: number) => byte >= 0xa1 && byte <= 0xfc, bytes: macBytes(0x5c) }],
	[10008, { lead: (byte: number) => byte >= 0xa1 && byte <= 0xfc, bytes: macBytes(0xfc) }]
])

interface Decoder {
	decode(input: Uint8Array): string
}

type DecoderConstructor = new (label: string) => Decoder

const decoders = new Map<string, Decoder | null>()

function decoderFor(label: string): Decoder | null {
	const cached = decoders.get(label)

	if (cached !== undefined) return cached

	const constructor = (globalThis as { TextDecoder?: DecoderConstructor }).TextDecoder
	let decoder: Decoder | null = null

	if (typeof constructor === "function") {
		try {
			decoder = new constructor(label)
		} catch {
			decoder = null
		}
	}

	decoders.set(label, decoder)

	return decoder
}

// Whether `codepage` decodes as itself here (false: Windows-1252 stands in).
export function codepageSupported(codepage: number): boolean {
	if (codepage === SYMBOL_CODEPAGE || codepage === 1252 || TABLES.has(codepage)) return true

	const label = LABELS.get(codepage)

	return label !== undefined && decoderFor(label) !== null
}

// Bytes through a table of 0x80..0xFF (bytes below are ASCII), in chunks that keep fromCharCode's arguments small.
function singleByte(bytes: Uint8Array, start: number, end: number, high: readonly number[]): string {
	let out = ""

	for (let at = start; at < end; at += 4096) {
		const stop = Math.min(end, at + 4096)
		const units = new Array<number>(stop - at)

		for (let i = at; i < stop; i++) {
			const byte = bytes[i] ?? 0

			units[i - at] = byte < 0x80 ? byte : (high[byte - 0x80] ?? byte)
		}

		out += String.fromCharCode(...units)
	}

	return out
}

// A Mac CJK run: the Windows decoder between the single-byte extras, which it would misread.
function decodeMacExtras(decoder: Decoder, bytes: Uint8Array, start: number, end: number, extras: MacExtras): string {
	let out = ""
	let from = start
	let i = start

	while (i < end) {
		const byte = bytes[i] ?? 0

		if (byte < 0x80) {
			i++

			continue
		}

		if (extras.lead(byte)) {
			i += 2

			continue
		}

		const extra = extras.bytes.get(byte)

		if (extra !== undefined) {
			if (i > from) out += decoder.decode(bytes.subarray(from, i))

			out += String.fromCharCode(extra)
			from = i + 1
		}

		i++
	}

	return from < end ? out + decoder.decode(bytes.subarray(from, end)) : out
}

// Bytes in a code page as UTF-16. Symbol-charset bytes become U+F020..U+F0FF, where Word keeps symbol-font
// characters (spec, "Unicode RTF"); layout maps them through the font's symbol table.
export function decodeCodepage(bytes: Uint8Array, start: number, end: number, codepage: number): string {
	if (end <= start) return ""

	if (codepage === SYMBOL_CODEPAGE) {
		let out = ""

		for (let i = start; i < end; i++) {
			const byte = bytes[i] ?? 0

			out += String.fromCharCode(byte >= 0x20 ? 0xf000 + byte : byte)
		}

		return out
	}

	let ascii = true

	for (let i = start; i < end; i++) {
		if ((bytes[i] ?? 0) >= 0x80) {
			ascii = false

			break
		}
	}

	if (ascii) return singleByte(bytes, start, end, CP1252)

	if (codepage !== 1252) {
		const table = TABLES.get(codepage)

		if (table !== undefined) return singleByte(bytes, start, end, table)

		const label = LABELS.get(codepage)
		const decoder = label === undefined ? null : decoderFor(label)

		if (decoder !== null) {
			const extras = MAC_EXTRAS.get(codepage)

			return extras === undefined ? decoder.decode(bytes.subarray(start, end)) : decodeMacExtras(decoder, bytes, start, end, extras)
		}
	}

	return singleByte(bytes, start, end, CP1252)
}
